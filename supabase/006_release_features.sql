create extension if not exists pgcrypto;

create table if not exists public.direct_conversations (
  id uuid primary key default gen_random_uuid(),
  direct_key text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.direct_conversation_members (
  conversation_id uuid not null references public.direct_conversations(id) on delete cascade,
  user_id text not null references public.profiles(id) on delete cascade,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.direct_conversations(id) on delete cascade,
  sender_id text not null references public.profiles(id) on delete cascade,
  text text not null check (char_length(trim(text)) > 0 and char_length(text) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id text not null references public.profiles(id) on delete cascade,
  actor_id text references public.profiles(id) on delete set null,
  type text not null check (type in ('comment', 'like', 'repost', 'bookmark', 'message')),
  post_id bigint references public.posts(id) on delete cascade,
  comment_id bigint references public.comments(id) on delete cascade,
  message_id bigint references public.direct_messages(id) on delete cascade,
  text text not null,
  read_at timestamptz,
  dedupe_key text unique,
  created_at timestamptz not null default now()
);

create index if not exists direct_conversation_members_user_idx on public.direct_conversation_members (user_id);
create index if not exists direct_messages_conversation_created_idx on public.direct_messages (conversation_id, created_at desc);
create index if not exists notifications_recipient_created_idx on public.notifications (recipient_id, created_at desc);
create index if not exists notifications_recipient_unread_idx on public.notifications (recipient_id) where read_at is null;

alter table public.direct_conversations enable row level security;
alter table public.direct_conversation_members enable row level security;
alter table public.direct_messages enable row level security;
alter table public.notifications enable row level security;

create or replace function public.is_conversation_member(target_conversation_id uuid, target_user_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.direct_conversation_members member
    where member.conversation_id = target_conversation_id
      and member.user_id = target_user_id
  );
$$;


