create or replace function public.safe_create_notification(
  target_recipient_id text,
  target_actor_id text,
  target_type text,
  target_post_id bigint,
  target_comment_id bigint,
  target_message_id bigint,
  target_text text,
  target_dedupe_key text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if target_recipient_id is null or target_recipient_id = target_actor_id then
    return;
  end if;

  insert into public.notifications (
    recipient_id,
    actor_id,
    type,
    post_id,
    comment_id,
    message_id,
    text,
    dedupe_key
  )
  values (
    target_recipient_id,
    target_actor_id,
    target_type,
    target_post_id,
    target_comment_id,
    target_message_id,
    target_text,
    target_dedupe_key
  )
  on conflict (dedupe_key) do update set
    text = excluded.text,
    read_at = null,
    created_at = now();
end;
$$;

revoke all on function public.safe_create_notification(text, text, text, bigint, bigint, bigint, text, text) from public, anon, authenticated;

create or replace function public.notify_post_comment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recipient_id text;
  actor_name text;
begin
  select owner_id into recipient_id from public.posts where id = new.post_id;
  select name into actor_name from public.profiles where id = new.author_id;

  perform public.safe_create_notification(
    recipient_id,
    new.author_id,
    'comment',
    new.post_id,
    new.id,
    null,
    coalesce(actor_name, 'Участник') || ' ответил(а) на ваш пост',
    'comment:' || new.id::text
  );

  return new;
end;
$$;

create or replace function public.notify_post_reaction()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recipient_id text;
  actor_name text;
  action_text text;
begin
  select owner_id into recipient_id from public.posts where id = new.post_id;
  select name into actor_name from public.profiles where id = new.user_id;

  action_text := case new.type
    when 'like' then 'поставил(а) лайк'
    when 'repost' then 'сделал(а) репост'
    when 'bookmark' then 'добавил(а) пост в избранное'
    else 'обновил(а) реакцию'
  end;

  perform public.safe_create_notification(
    recipient_id,
    new.user_id,
    new.type,
    new.post_id,
    null,
    null,
    coalesce(actor_name, 'Участник') || ' ' || action_text,
    'reaction:' || new.type || ':' || new.post_id::text || ':' || new.user_id
  );

  return new;
end;
$$;

create or replace function public.notify_direct_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  member_record record;
  actor_name text;
begin
  select name into actor_name from public.profiles where id = new.sender_id;

  for member_record in
    select user_id
    from public.direct_conversation_members
    where conversation_id = new.conversation_id
      and user_id <> new.sender_id
  loop
    perform public.safe_create_notification(
      member_record.user_id,
      new.sender_id,
      'message',
      null,
      null,
      new.id,
      coalesce(actor_name, 'Участник') || ' написал(а) сообщение',
      'message:' || new.id::text || ':' || member_record.user_id
    );
  end loop;

  return new;
end;
$$;

revoke all on function public.notify_post_comment() from public, anon, authenticated;
